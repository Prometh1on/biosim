"""
SBML exporter for the glucose/insulin pathway model.

Generates valid SBML Level 2 Version 4 XML from a GlucoseInsulinPathway
instance. SBML is the standard interchange format for systems biology
models — it can be loaded into COPASI, CellDesigner, JWS Online,
BioNetGen, and any tool supporting the libSBML library.

The ODE system is encoded as SBML rate rules (assignmentRule is used for
derived quantities; rateRule is used for state variables). This is
the correct encoding for ODE models in SBML — not as reactions —
because the model uses non-mass-action kinetics throughout.

What is NOT exported (so an exported model can differ from a simulation):
  - the dG-driven first-phase insulin secretion term (see _rate_rules);
  - every drug, disease and personalisation effect, and every coupled
    extension pathway (the exporter takes a bare GlucoseInsulinPathway),
    including MealAbsorptionPathway's stomach/gut states used with GLP-1
    drugs. Meals are exported with their closed-form Ra(t): single-
    exponential, or two-compartment (since 2026-11-17).

Output can be validated at https://validator.sbml.org/

Literature: Hucka et al. 2003, Bioinformatics. PMID:12611808
"""

from __future__ import annotations

from typing import Optional


# Internal unit: minutes. SBML unit definitions use SI base units.
_SBML_HEADER = '''<?xml version="1.0" encoding="UTF-8"?>
<sbml xmlns="http://www.sbml.org/sbml/level2/version4"
      xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
      level="2" version="4">
'''

_MODEL_NOTES = """
  <notes>
    <body xmlns="http://www.w3.org/1999/xhtml">
      <p>Glucose-insulin-IGF1-mTOR-AMPK axis ODE model.</p>
      <p>Adapted from Bergman minimal model (Bergman et al. 1981, J Clin Invest 68:1456)
         with extensions for IGF-1 (Le Roith 1997), mTOR (Sarbassov 2005),
         and AMPK (Hardie 2012).</p>
      <p>Generated by biosim_expert.sbml_export. Model version: glucose_insulin_v1.0</p>
      <p>Internal time unit: minutes. Concentrations: mM (glucose), pM (insulin), nM (IGF-1).</p>
    </body>
  </notes>"""


def _indent(xml: str, spaces: int) -> str:
    pad = " " * spaces
    return "\n".join(pad + line if line.strip() else line for line in xml.split("\n"))


class SBMLExporter:
    """
    Exports a GlucoseInsulinPathway to SBML Level 2 Version 4.

    Usage:
        from biosim_ode import GlucoseInsulinPathway, PathwayParameters
        from biosim_expert import SBMLExporter

        pathway = GlucoseInsulinPathway()
        sbml_xml = SBMLExporter().export(pathway)
        with open("glucose_insulin.xml", "w") as f:
            f.write(sbml_xml)
    """

    def export(
        self,
        pathway,                    # GlucoseInsulinPathway
        model_id: str = "glucose_insulin_v1",
        model_name: str = "Glucose-Insulin-IGF1-mTOR-AMPK axis",
        include_notes: bool = True,
    ) -> str:
        """
        Generate SBML XML string for the given pathway.

        Args:
            pathway:      GlucoseInsulinPathway instance
            model_id:     SBML model identifier (must be valid XML ID)
            model_name:   Human-readable model name
            include_notes: Include provenance notes in SBML output

        Returns:
            Valid SBML Level 2 Version 4 XML string
        """
        p = pathway.params
        y0 = pathway.y0
        lines = [_SBML_HEADER]
        lines.append(f'  <model id="{model_id}" name="{model_name}">')

        if include_notes:
            lines.append(_MODEL_NOTES)

        # Unit definitions
        lines.append(self._unit_definitions())

        # Compartments
        lines.append("  <listOfCompartments>")
        lines.append('    <compartment id="blood" name="blood plasma" size="1" units="litre"/>');
        lines.append("  </listOfCompartments>")

        # Species (state variables)
        lines.append("  <listOfSpecies>")
        species_data = [
            ("G",    "Blood glucose",              y0[0], "mM",            False),
            ("I",    "Plasma insulin",             y0[1], "pM",            False),
            ("X",    "Remote insulin effect",      y0[2], "per_minute",    False),
            ("IGF1", "Plasma IGF-1",               y0[3], "nM",            False),
            ("mTOR", "mTORC1 fractional activity", y0[4], "dimensionless", False),
            ("AMPK", "AMPK fractional activity",   y0[5], "dimensionless", False),
        ]
        for sid, sname, ic, unit, bc in species_data:
            lines.append(
                f'    <species id="{sid}" name="{sname}" compartment="blood" '
                f'initialConcentration="{ic:.6g}" units="{unit}" '
                f'boundaryCondition="{str(bc).lower()}"/>'
            )
        lines.append("  </listOfSpecies>")

        # Parameters
        lines.append("  <listOfParameters>")
        # basal_frac and F_secretion_basal are computed properties/local
        # values in GlucoseInsulinPathway.dydt() (functions of Gb,
        # G_threshold, KG_secretion, ke, Ib, all already exported below),
        # not raw PathwayParameters fields -- baked in as constants here,
        # exactly like every other exported parameter already bakes in
        # the live Python object's current value rather than re-deriving
        # a formula in MathML.
        Gb_above = max(p.Gb - p.G_threshold, 0.0)
        basal_frac = Gb_above / (p.KG_secretion + Gb_above) if Gb_above > 0 else 0.0
        params_data = [
            ("Gb",               p.Gb,               "mM",            "Basal glucose"),
            ("Ib",               p.Ib,               "pM",            "Basal insulin"),
            ("p1",               p.p1,               "per_minute",    "Glucose effectiveness"),
            ("p2",               p.p2,               "per_minute",    "X compartment clearance"),
            ("p3",               p.p3,               "per_minute_pM", "Insulin action (p3)"),
            ("extra_g_clearance", p.extra_g_clearance, "per_minute",  "Additional glucose clearance"),
            ("ke",               p.ke,               "per_minute",    "Insulin elimination rate"),
            ("G_threshold",      p.G_threshold,      "mM",            "Glucose secretion threshold"),
            ("KG_secretion",     p.KG_secretion,     "mM",            "Michaelis constant for secretion"),
            ("F_secretion_basal", p.F_secretion_basal, "pM_per_minute", "Beta-cell secretion scale factor"),
            ("basal_frac",       basal_frac,         "dimensionless", "Secretion fraction at basal glucose"),
            ("secretion_scale",  p.secretion_scale,  "dimensionless", "Secretion scale modifier"),
            ("k_igf1_clear",     p.k_igf1_clear,     "per_minute",    "IGF-1 clearance rate"),
            ("IGF1b",            p.IGF1b,            "nM",            "Basal IGF-1"),
            ("IGF1_ins_sensitivity", p.IGF1_ins_sensitivity, "dimensionless", "IGF-1/insulin coupling"),
            ("EC50_mTOR",        p.EC50_mTOR,        "pM",            "mTOR half-maximal insulin"),
            ("n_mTOR",           p.n_mTOR,           "dimensionless", "mTOR Hill coefficient"),
            ("k_mTOR",           p.k_mTOR,           "per_minute",    "mTOR relaxation rate"),
            ("EC50_AMPK",        p.EC50_AMPK,        "pM",            "AMPK half-maximal inhibition"),
            ("n_AMPK",           p.n_AMPK,           "dimensionless", "AMPK Hill coefficient"),
            ("k_AMPK",           p.k_AMPK,           "per_minute",    "AMPK relaxation rate"),
            ("AMPK_max",         p.AMPK_max,         "dimensionless", "Maximum AMPK activity"),
        ]
        for pid, pval, punit, pname in params_data:
            lines.append(
                f'    <parameter id="{pid}" name="{pname}" value="{pval:.6g}" '
                f'units="{punit}" constant="true"/>'
            )
        for i, meal in enumerate(pathway.meals):
            lines.append(
                f'    <parameter id="meal{i}_D_eff" name="Meal {i} effective dose" '
                f'value="{meal.D_eff_mM:.6g}" units="mM" constant="true"/>'
            )
            if meal.absorption_model is None:
                lines.append(
                    f'    <parameter id="meal{i}_kabs" name="Meal {i} absorption rate" '
                    f'value="{meal.kabs:.6g}" units="per_minute" constant="true"/>'
                )
            else:
                model = meal.absorption_model
                lines.append(
                    f'    <parameter id="meal{i}_k_emptying" name="Meal {i} stomach emptying rate" '
                    f'value="{model.k_emptying:.10g}" units="per_minute" constant="true"/>'
                )
                lines.append(
                    f'    <parameter id="meal{i}_k_absorption" name="Meal {i} gut absorption rate" '
                    f'value="{model.k_absorption:.10g}" units="per_minute" constant="true"/>'
                )
            lines.append(
                f'    <parameter id="meal{i}_time_min" name="Meal {i} onset time" '
                f'value="{meal.time_min:.6g}" units="minute" constant="true"/>'
            )
        lines.append("  </listOfParameters>")

        # Rate rules (the ODEs)
        lines.append("  <listOfRules>")
        lines.extend(self._rate_rules(meals=pathway.meals))
        lines.append("  </listOfRules>")

        lines.append("  </model>")
        lines.append("</sbml>")
        return "\n".join(lines)

    def _unit_definitions(self) -> str:
        return """  <listOfUnitDefinitions>
    <unitDefinition id="per_minute">
      <listOfUnits><unit kind="second" exponent="-1" multiplier="0.016667"/></listOfUnits>
    </unitDefinition>
    <unitDefinition id="minute">
      <listOfUnits><unit kind="second" exponent="1" multiplier="60"/></listOfUnits>
    </unitDefinition>
    <unitDefinition id="mM">
      <listOfUnits><unit kind="mole" exponent="1" scale="-3"/><unit kind="litre" exponent="-1"/></listOfUnits>
    </unitDefinition>
    <unitDefinition id="pM">
      <listOfUnits><unit kind="mole" exponent="1" scale="-12"/><unit kind="litre" exponent="-1"/></listOfUnits>
    </unitDefinition>
    <unitDefinition id="nM">
      <listOfUnits><unit kind="mole" exponent="1" scale="-9"/><unit kind="litre" exponent="-1"/></listOfUnits>
    </unitDefinition>
    <unitDefinition id="per_minute_pM">
      <listOfUnits>
        <unit kind="second" exponent="-2" multiplier="0.016667"/>
        <unit kind="mole" exponent="-1" scale="-12"/>
        <unit kind="litre" exponent="1"/>
      </listOfUnits>
    </unitDefinition>
    <unitDefinition id="pM_per_minute">
      <listOfUnits>
        <unit kind="mole" exponent="1" scale="-12"/>
        <unit kind="litre" exponent="-1"/>
        <unit kind="second" exponent="-1" multiplier="0.016667"/>
      </listOfUnits>
    </unitDefinition>
  </listOfUnitDefinitions>"""

    _TIME = (
        '<csymbol encoding="text" '
        'definitionURL="http://www.sbml.org/sbml/symbols/time">t</csymbol>'
    )

    def _meal_ra_term(self, i: int, two_compartment: bool = False) -> str:
        """
        MathML for one meal's Ra(t), 0 before the meal starts.

        Single-exponential (a meal with kabs set):
            D_eff*kabs*exp(-kabs*(t-time_min))
        Two-compartment (GutAbsorptionModel: the default meal and GI meals,
        encoded since 2026-11-17), with ke = k_emptying, ka = k_absorption:
            D_eff*ka*ke/(ka-ke) * (exp(-ke*(t-time_min)) - exp(-ka*(t-time_min)))
        """
        if two_compartment:
            return self._two_compartment_ra_term(i)
        return f"""<piecewise>
              <piece>
                <apply><times/>
                  <ci>meal{i}_D_eff</ci><ci>meal{i}_kabs</ci>
                  <apply><exp/>
                    <apply><times/>
                      <apply><minus/><ci>meal{i}_kabs</ci></apply>
                      <apply><minus/>{self._TIME}<ci>meal{i}_time_min</ci></apply>
                    </apply>
                  </apply>
                </apply>
                <apply><geq/>{self._TIME}<ci>meal{i}_time_min</ci></apply>
              </piece>
              <otherwise><cn>0</cn></otherwise>
            </piecewise>"""

    def _two_compartment_ra_term(self, i: int) -> str:
        ke, ka = f"<ci>meal{i}_k_emptying</ci>", f"<ci>meal{i}_k_absorption</ci>"
        dt = f"<apply><minus/>{self._TIME}<ci>meal{i}_time_min</ci></apply>"
        return f"""<piecewise>
              <piece>
                <apply><times/>
                  <apply><divide/>
                    <apply><times/><ci>meal{i}_D_eff</ci>{ka}{ke}</apply>
                    <apply><minus/>{ka}{ke}</apply>
                  </apply>
                  <apply><minus/>
                    <apply><exp/><apply><times/><apply><minus/>{ke}</apply>{dt}</apply></apply>
                    <apply><exp/><apply><times/><apply><minus/>{ka}</apply>{dt}</apply></apply>
                  </apply>
                </apply>
                <apply><geq/>{self._TIME}<ci>meal{i}_time_min</ci></apply>
              </piece>
              <otherwise><cn>0</cn></otherwise>
            </piecewise>"""

    def _total_ra_mathml(self, meals: list) -> str:
        """Sum of every meal's Ra(t) term. <cn>0</cn> if there are no meals."""
        terms = [
            self._meal_ra_term(i, two_compartment=meal.absorption_model is not None)
            for i, meal in enumerate(meals)
        ]
        if not terms:
            return "<cn>0</cn>"
        if len(terms) == 1:
            return terms[0]
        return "<apply><plus/>" + "".join(terms) + "</apply>"

    @staticmethod
    def _dG_above_mathml() -> str:
        """max(G - G_threshold, 0), used by the delta_secretion term."""
        return """<piecewise>
              <piece>
                <apply><minus/><ci>G</ci><ci>G_threshold</ci></apply>
                <apply><gt/><ci>G</ci><ci>G_threshold</ci></apply>
              </piece>
              <otherwise><cn>0</cn></otherwise>
            </piecewise>"""

    def _rate_rules(self, meals: Optional[list] = None) -> list[str]:
        """Generate rate rule MathML for each ODE."""
        rules = []
        dG_above = self._dG_above_mathml()

        # dG/dt = Ra(t) - ( p1 + X + extra_g_clearance ) * (G - Gb)
        rules.append(f"""    <rateRule variable="G">
      <math xmlns="http://www.w3.org/1998/Math/MathML">
        <apply><minus/>
          {self._total_ra_mathml(meals or [])}
          <apply><times/>
            <apply><plus/><ci>p1</ci><ci>X</ci><ci>extra_g_clearance</ci></apply>
            <apply><minus/><ci>G</ci><ci>Gb</ci></apply>
          </apply>
        </apply>
      </math>
    </rateRule>""")

        # dI/dt = -ke*(I-Ib) + F_secretion_basal*(current_frac - basal_frac)*secretion_scale
        # current_frac = max(G-G_threshold,0) / (KG_secretion + max(G-G_threshold,0))
        # (first_phase_secretion, the dynamic/first-phase component driven by
        # the instantaneous rate of change of G rather than G's value, is not
        # encoded -- see this module's docstring for why.)
        rules.append(f"""    <rateRule variable="I">
      <math xmlns="http://www.w3.org/1998/Math/MathML">
        <apply><plus/>
          <apply><minus/>
            <cn>0</cn>
            <apply><times/><ci>ke</ci><apply><minus/><ci>I</ci><ci>Ib</ci></apply></apply>
          </apply>
          <apply><times/>
            <ci>F_secretion_basal</ci>
            <apply><minus/>
              <apply><divide/>{dG_above}
                <apply><plus/><ci>KG_secretion</ci>{dG_above}</apply>
              </apply>
              <ci>basal_frac</ci>
            </apply>
            <ci>secretion_scale</ci>
          </apply>
        </apply>
      </math>
    </rateRule>""")

        # dX/dt = -p2*X + p3*max(I-Ib, 0)
        rules.append("""    <rateRule variable="X">
      <math xmlns="http://www.w3.org/1998/Math/MathML">
        <apply><plus/>
          <apply><times/><apply><minus/><ci>p2</ci></apply><ci>X</ci></apply>
          <apply><times/><ci>p3</ci>
            <piecewise>
              <piece>
                <apply><minus/><ci>I</ci><ci>Ib</ci></apply>
                <apply><gt/><ci>I</ci><ci>Ib</ci></apply>
              </piece>
              <otherwise><cn>0</cn></otherwise>
            </piecewise>
          </apply>
        </apply>
      </math>
    </rateRule>""")

        # dIGF1/dt = max(k_igf1_clear*IGF1b*(1 + IGF1_ins_sensitivity*(I/Ib - 1)), 0)
        #            - k_igf1_clear*IGF1
        # Production scales with insulin (chronic insulin -> IGF-1 axis) --
        # this term was entirely missing from an earlier version of this
        # export (constant production, no I-dependence at all), caught by
        # TestSBMLExportMatchesRealODE comparing against the real dIGF1/dt.
        rules.append("""    <rateRule variable="IGF1">
      <math xmlns="http://www.w3.org/1998/Math/MathML">
        <apply><minus/>
          <piecewise>
            <piece>
              <apply><times/><ci>k_igf1_clear</ci><ci>IGF1b</ci>
                <apply><plus/><cn>1</cn>
                  <apply><times/><ci>IGF1_ins_sensitivity</ci>
                    <apply><minus/><apply><divide/><ci>I</ci><ci>Ib</ci></apply><cn>1</cn></apply>
                  </apply>
                </apply>
              </apply>
              <apply><gt/>
                <apply><times/><ci>k_igf1_clear</ci><ci>IGF1b</ci>
                  <apply><plus/><cn>1</cn>
                    <apply><times/><ci>IGF1_ins_sensitivity</ci>
                      <apply><minus/><apply><divide/><ci>I</ci><ci>Ib</ci></apply><cn>1</cn></apply>
                    </apply>
                  </apply>
                </apply>
                <cn>0</cn>
              </apply>
            </piece>
            <otherwise><cn>0</cn></otherwise>
          </piecewise>
          <apply><times/><ci>k_igf1_clear</ci><ci>IGF1</ci></apply>
        </apply>
      </math>
    </rateRule>""")

        # dmTOR/dt = k_mTOR * (H(I,EC50_mTOR,n_mTOR) - mTOR)
        rules.append("""    <rateRule variable="mTOR">
      <math xmlns="http://www.w3.org/1998/Math/MathML">
        <apply><times/><ci>k_mTOR</ci>
          <apply><minus/>
            <apply><divide/>
              <apply><power/><ci>I</ci><ci>n_mTOR</ci></apply>
              <apply><plus/>
                <apply><power/><ci>EC50_mTOR</ci><ci>n_mTOR</ci></apply>
                <apply><power/><ci>I</ci><ci>n_mTOR</ci></apply>
              </apply>
            </apply>
            <ci>mTOR</ci>
          </apply>
        </apply>
      </math>
    </rateRule>""")

        # dAMPK/dt = k_AMPK * (AMPK_max * H_inhib(I,EC50_AMPK,n_AMPK) - AMPK)
        rules.append("""    <rateRule variable="AMPK">
      <math xmlns="http://www.w3.org/1998/Math/MathML">
        <apply><times/><ci>k_AMPK</ci>
          <apply><minus/>
            <apply><times/><ci>AMPK_max</ci>
            <apply><divide/>
              <apply><power/><ci>EC50_AMPK</ci><ci>n_AMPK</ci></apply>
              <apply><plus/>
                <apply><power/><ci>EC50_AMPK</ci><ci>n_AMPK</ci></apply>
                <apply><power/><ci>I</ci><ci>n_AMPK</ci></apply>
              </apply>
            </apply>
            </apply>
            <ci>AMPK</ci>
          </apply>
        </apply>
      </math>
    </rateRule>""")

        return rules
